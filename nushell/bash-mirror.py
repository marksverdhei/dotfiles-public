#!/usr/bin/python3
"""Generate nushell mirrors of the bash aliases and functions.

Bash stays the source of truth. This asks an interactive bash for its final
alias/function state (after ~/.bashrc.d and the private layer) and writes:

  $NU_AUTOLOAD/bash-mirror.nu  nu commands, autoloaded by nushell
  $MIRROR_DIR/shim.sh          bash state the wrappers source (functions,
                               aliases, non-exported shell vars)

Translation tiers:
  native   cd/z aliases with a plain target   -> `def --env` (changes nu's cwd)
  alias    plain command + literal args        -> nu `alias` (fast, completes)
  wrapper  anything else                       -> runs in bash via the shim
Names already defined natively in config.nu, or nu builtins, are skipped.

Usage: bash-mirror.py [--quiet]
"""
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile

HOME = os.path.expanduser("~")
NU_CONFIG = os.path.join(HOME, ".config/nushell")
NU_AUTOLOAD = os.path.join(NU_CONFIG, "autoload")
MIRROR_DIR = os.path.join(HOME, ".local/share/nushell/bash-mirror")
OUT_NU = os.path.join(NU_AUTOLOAD, "bash-mirror.nu")
SHIM = os.path.join(MIRROR_DIR, "shim.sh")

# Runs inside `bash -i`, after the full rc chain has loaded.
DUMP = r'''
out=$BASH_MIRROR_OUT
declare -F | awk '{print $3}' > "$out/functions"
alias -p > "$out/aliases"
{
  echo '# GENERATED by dotfiles/nushell/bash-mirror.py - do not edit'
  shopt -p   # same parse options as the live shell (extglob in function bodies)
  for v in $(compgen -v); do
    case $v in
      BASH*|_*|PS?|PROMPT_*|HIST*|COMP*|FUNCNAME|GROUPS|DIRSTACK|EUID|UID|PPID|\
      SHELLOPTS|RANDOM|SECONDS|LINENO|SRANDOM|EPOCH*|OPT*|IFS|COLUMNS|LINES|\
      PWD|OLDPWD|SHLVL|MAIL*|HOSTNAME|HOSTTYPE|MACHTYPE|OSTYPE|PATH|TERM|\
      STARSHIP*|PIPESTATUS|READLINE*|v|out) continue ;;
    esac
    flags=$(declare -p "$v" 2>/dev/null | cut -d' ' -f2)
    [[ $flags == *x* || $flags == *r* ]] && continue
    declare -p "$v"
  done
  declare -f
  # `r` (exec bash) inside a mirrored function would strand you in bash.
  echo 'exec() { [[ $# -eq 1 && $1 == bash ]] && return 0; builtin exec "$@"; }'
  echo 'shopt -s expand_aliases'
  alias -p
} > "$out/shim.sh"
'''

SKIP_FUNC_PREFIX = ("_", "starship_", "nvm_", "__")
SKIP_FUNC = {"command_not_found_handle", "z", "zi"}
METACHARS = set("$`|;&<>(){}*?~!\n\\")
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")
BARE = re.compile(r"^[A-Za-z0-9_./:@%+,=-]+$")


def nu_commands():
    """Single-word nu builtins/keywords, which mirrors must not shadow."""
    out = subprocess.run(
        ["nu", "-n", "-c",
         'scope commands | where type != "external" | get name | to json'],
        capture_output=True, text=True, check=True).stdout
    return {n for n in json.loads(out) if " " not in n}


def native_names():
    """Commands config.nu defines natively; those win over the mirror."""
    names = {"z", "zi"}  # zoxide's own nushell integration
    path = os.path.join(NU_CONFIG, "config.nu")
    pat = re.compile(r"^\s*(?:export\s+)?(?:def|alias)\s+(?:--\w+\s+)*([\w-]+)")
    try:
        with open(path) as f:
            for line in f:
                m = pat.match(line)
                if m:
                    names.add(m.group(1))
    except OSError:
        pass
    return names


def dump_bash(tmp):
    env = dict(os.environ, BASH_MIRROR_OUT=tmp)
    subprocess.run(["bash", "-ic", DUMP], env=env, stdin=subprocess.DEVNULL,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    with open(os.path.join(tmp, "functions")) as f:
        functions = [l.strip() for l in f if l.strip()]
    aliases = {}
    with open(os.path.join(tmp, "aliases")) as f:
        for line in f:
            if not line.startswith("alias "):
                continue
            try:
                name, body = shlex.split(line[6:])[0].split("=", 1)
            except (ValueError, IndexError):
                continue
            aliases[name] = body
    with open(os.path.join(tmp, "shim.sh")) as f:
        shim = f.read()
    return functions, aliases, shim


def nu_word(w):
    if BARE.match(w):
        return w
    if "'" not in w:
        return f"'{w}'"
    return json.dumps(w)  # nu double-quoted strings take JSON escapes


def nu_path(tok):
    """Translate a cd target to nu, or None if it is not a plain path."""
    if tok in ("-", "..", "../..", "../../.."):
        return tok
    if tok in ("$(realpath .)", "$(rp)"):
        return "(pwd | path expand)"
    m = re.fullmatch(r"\$\{?([A-Z_][A-Z0-9_]*)\}?(/[\w./-]*)?", tok)
    if m:
        var, rest = m.group(1), m.group(2) or ""
        if var == "HOSTNAME":
            return None
        return f'$"($env.{var}){rest}"'
    m = re.fullmatch(r"\$\{?([A-Z_][A-Z0-9_]*)\}?(/[\w./-]*)?/\$\{?HOSTNAME\}?", tok)
    if m:
        return f'$"($env.{m.group(1)}){m.group(2) or ""}/(sys host | get hostname)"'
    if BARE.match(tok) or tok.startswith("~/"):
        return nu_word(tok)
    return None


def cd_alias(body):
    """`cd X` / `z X` with a plain target -> nu body, else None."""
    parts = body.split(None, 1)
    if not parts or parts[0] not in ("cd", "z"):
        return None
    if len(parts) == 1:
        return "cd ~"
    target = nu_path(parts[1].strip().strip('"'))
    if target is None:
        return None
    return f"{'z' if parts[0] == 'z' else 'cd'} {target}"


def simple_alias(body, aliases, defs):
    if any(c in METACHARS for c in body):
        return None
    try:
        words = shlex.split(body)
    except ValueError:
        return None
    if not words or "=" in words[0] or words[0] in aliases:
        return None
    head = words[0] if words[0] in defs else f"^{words[0]}"
    return " ".join([head] + [nu_word(w) for w in words[1:]])


def main():
    quiet = "--quiet" in sys.argv
    os.makedirs(NU_AUTOLOAD, exist_ok=True)
    os.makedirs(MIRROR_DIR, mode=0o700, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        functions, aliases, shim = dump_bash(tmp)

    taken = nu_commands() | native_names()
    skipped, wrappers, natives, plain = [], [], [], []

    funcs = [f for f in functions
             if not f.startswith(SKIP_FUNC_PREFIX) and f not in SKIP_FUNC
             and f not in aliases]
    defs = set()
    for name in funcs:
        if not IDENT.match(name) or name in taken:
            skipped.append(name)
            continue
        defs.add(name)
        wrappers.append(name)

    alias_lines = []
    for name, body in sorted(aliases.items()):
        if not IDENT.match(name) or name in taken:
            skipped.append(name)
            continue
        cd = cd_alias(body)
        if cd:
            natives.append(f"def --env {name} [] {{ {cd} }}")
            continue
        simple = simple_alias(body, aliases, defs)
        if simple:
            alias_lines.append(f"alias {name} = {simple}")
            plain.append(name)
        else:
            defs.add(name)
            wrappers.append(name)

    old_umask = os.umask(0o077)  # shim may hold private vars
    try:
        with open(SHIM, "w") as f:
            f.write(shim)
        lines = [
            "# GENERATED by ~/dotfiles/nushell/bash-mirror.py - do not edit.",
            "# Regenerated automatically by env.nu when any bash rc file changes;",
            "# force it with `bash-mirror`.",
            f"# {len(natives)} native cd, {len(plain)} aliases, "
            f"{len(wrappers)} bash wrappers, {len(skipped)} skipped:",
            "#   " + " ".join(sorted(skipped)),
            "",
            "# Run a mirrored bash function/alias with the full bash state loaded.",
            "def --wrapped bash-mirror-run [name: string, ...args] {",
            f"    ^bash -c 'source \"$0\"; eval \"$1 \\\"\\${{@:2}}\\\"\"' {nu_word(SHIM)} $name ...$args",
            "}",
            "",
        ]
        lines += [f"def --wrapped {n} [...args] {{ bash-mirror-run {n} ...$args }}"
                  for n in wrappers]
        lines += [""] + natives + [""] + alias_lines + [""]
        with open(OUT_NU, "w") as f:
            f.write("\n".join(lines))
    finally:
        os.umask(old_umask)

    if not quiet:
        print(f"bash-mirror: {len(natives)} native cd, {len(plain)} aliases, "
              f"{len(wrappers)} bash wrappers, {len(skipped)} skipped")
        print(f"  skipped (nu builtin or native in config.nu): {' '.join(sorted(skipped))}")


if __name__ == "__main__":
    main()
